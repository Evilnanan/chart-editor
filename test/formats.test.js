test('BMS import reads BPM, fractional measures, attached hearts and long notes',()=>{
  const chart=parseBms(bmsReference,'map3.bms');
  assert.equal(chart.scene,'scene_touhou');
  assert.equal(chart.notes.find(note=>note.heart).time,.5);
  assert.equal(chart.notes.find(note=>note.type==='long').end,2.5);
  assert.equal(chart.notes.filter(note=>note.type==='small_1').at(-1).speed,3);
  assert.equal(chart.tempos[0].bpm,180);
  const text=serializeBms(chart);
  assert.match(text,/#00102:0\.75/);
  assert.match(text,/#002SC:AA/);
  assert.match(text,/#002D3:0F/);
  const reopened=parseBms(text);
  assert.deepEqual(reopened.notes.map(note=>[note.type,note.time,note.end,note.speed]),chart.notes.map(note=>[note.type,note.time,note.end,note.speed]));
});

test('BMS time remains stable around newly authored tempo markers and short measures',()=>{
  const chart=testsChart();
  chart.notes=[makeNote('small_1',1.25,'air'),makeNote('long',2.42,'road',0,{end:2.92})];
  chart.tempos=[{id:uid(),time:1.75,bpm:150,numerator:3,denominator:4}];
  const reopened=parseBms(serializeBms(chart));
  assert.equal(reopened.tempos.find(item=>item.bpm===150).time,1.75);
  for(const [index,note] of reopened.notes.entries()) {
    assert.ok(Math.abs(chart.notes[index].time-note.time)<.002);
    assert.ok(Math.abs(chart.notes[index].end-note.end)<.002);
  }
});

test('MDM and Euterpe handle two difficulties with shared audio and per-map ratings',async()=>{
  const master=testsChart();
  master.notes=[makeNote('small_1',2,'air')];
  const hard=makeProject({...testsChart(),id:uid(),difficulty:'hard',level:'5',designer:'Another',notes:[makeNote('long',3,'road',0,{end:4})]});
  const assets={audio:music,extras:{}};
  for(const format of ['mdm','epk']) {
    const result=await exportFile(format,master,[master,hard],assets);
    const entries=unzipSync(await toBytes(result.blob));
    assert.ok(entries['map2.bms']&&entries['map3.bms']&&entries['music.ogg']);
    const reopened=await fromExport(result);
    assert.equal(reopened.documents.length,2);
    const byDifficulty=Object.fromEntries(reopened.documents.map(chart=>[chart.difficulty,chart]));
    assert.equal(byDifficulty.hard.designer,'Another');
    assert.equal(byDifficulty.hard.level,'5');
    assert.equal(byDifficulty.hard.notes[0].end,4);
    assert.deepEqual(await toBytes(reopened.assets.audio.blob),await toBytes(music.blob));
    if(format==='epk') {
      const manifest=decode(entries['manifest.epk']);
      assert.equal(manifest.schema,1);
      assert.deepEqual(Object.keys(manifest.meta.maps).sort(),['map2','map3']);
      assert.equal(manifest.meta.maps.map3.rating,'8');
      assert.equal(manifest.files['map2.bms'].size,entries['map2.bms'].length);
      assert.equal(manifest.files['music.ogg'].size,4);
    } else assert.equal(JSON.parse(strFromU8(entries['info.json'])).difficulty2,'5');
  }
});

test('Euterpe standalone manifest and current package schema preserve extra files',async()=>{
  const bms=strToU8(bmsReference);
  const talk=strToU8('dialogue');
  const native={schema:1,cid:42,meta:{name:'Euterpe reference',author:'Composer',bpm:120,bpm_min:100,bpm_max:180,scene:'scene_08',safe_for_streamer:true,
    maps:{map2:{rating:'6',charters:['One']},map3:{rating:'10.5',charters:['One','Two'],predicted_rating:9.9}}},files:{
    'map3.bms':{version:2,size:bms.length},'map3.talk':{version:1,size:talk.length},'cover.webp':{version:1,size:cover.blob.size},
  }};
  const manifest=encode(native);
  const metadata=(await openFiles([new File([manifest],'manifest.epk')]));
  assert.equal(metadata.documents[0].manifestOnly,true);
  metadata.documents[0].name='Edited title';
  const raw=await exportFile('epk-only',metadata.documents[0],metadata.documents,metadata.assets);
  const preserved=decode(await toBytes(raw.blob));
  assert.deepEqual(preserved.files,native.files);
  assert.equal(preserved.cid,42);
  assert.equal(preserved.meta.name,'Edited title');
  assert.equal(preserved.meta.bpm_min,100);
  assert.equal(preserved.meta.bpm_max,180);
  assert.equal(preserved.meta.maps.map2.rating,'6');
  const zip=zipSync({'manifest.epk':manifest,'map3.bms':bms,'map3.talk':talk,'cover.webp':await toBytes(cover.blob),'music.ogg':await toBytes(music.blob)});
  const loaded=await openFiles([new File([zip],'reference.zip')]);
  assert.equal(loaded.documents[0].level,'10.5');
  assert.equal(loaded.documents[0].designer,'One, Two');
  const output=unzipSync(await toBytes((await exportFile('epk',loaded.documents[0],loaded.documents,loaded.assets)).blob));
  assert.deepEqual(output['map3.talk'],talk);
  assert.ok(output['cover.webp']);
  assert.equal(decode(output['manifest.epk']).meta.maps.map3.predicted_rating,9.9);
});

test('project backup preserves all assets and reports target format losses',async()=>{
  const project=testsChart();
  project.notes=[makeNote('curvehold_blue',2,'air')];
  const assets={audio:music,cover,extras:{'video.mp4':new Blob(['video'])}};
  const result=await exportFile('json',project,[project],assets);
  const backup=await fromExport(result);
  assert.equal(backup.documents[0].notes[0].type,'curvehold_blue');
  assert.equal(await backup.assets.extras['video.mp4'].text(),'video');
  assert.deepEqual(await toBytes(backup.assets.cover.blob),await toBytes(cover.blob));
  assert.match(formatLoss('bms',project,[project]).join(' '),/curve holds/);
  assert.deepEqual(formatLoss('json',project,[project]),[]);
});

test('grid snapping and entrance constraints account for a tempo and meter transition',()=>{
  const project=testsChart();
  project.tempos=[{id:uid(),time:2,bpm:150,numerator:3,denominator:4}];
  assert.equal(snapTime(project,2.19,4),2.2);
  assert.ok(gridPoints(project,0,4,4).some(point=>point.time===2&&point.kind==='bar'));
  const note=makeNote('assault',1,'air');
  mirrorNote(note);
  assert.equal(note.track,'road');
  assert.ok(directions(note.type).includes(note.direction));
});


test('CustomPlay short notes and short curves preserve their native type',()=>{
  const chart=testsChart();
  chart.notes=[makeNote('long_short',1,'air'),makeNote('curvehold_red_short',2,'road')];
  const bytes=serializeMdcpmf(chart);
  const text=decodeMdcpmf(bytes);
  assert.match(text,/note\(long_short_air,1,normal,-1,NULL,2\);/);
  assert.match(text,/note\(curvehold_red_short,2,curve/);
  const reopened=parseMdcpmf(bytes);
  assert.deepEqual(reopened.notes.map(note=>note.type),['long_short','curvehold_red_short']);
});
